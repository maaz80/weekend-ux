// Prefetch all global and page data on the server during build/SSR so static HTML has live database data without fallback
async function getLayoutInitialData() {
  try {
    await connectDB();
    const [
      navbarDoc,
      footerGlobalDoc,
      footerColumnsDocs,
      homeDoc,
      blogDoc,
      coursesDoc,
      testimonialDocs,
      faqDoc,
      locationDocs
    ] = await Promise.all([
      NavbarModel.findOne().lean(),
      FooterModel.findOne({ isGlobal: true }).lean(),
      FooterModel.find({ isGlobal: { $ne: true } }).sort({ order: 1 }).lean(),
      HomeModel.findOne().lean(),
      BlogModel.findOne().lean(),
      CoursesModel.findOne().lean(),
      TestimonialModel.find().lean(),
      FaqModel.findOne({ pageSlug: "home" }).lean(),
      LocationModel.find().lean()
    ]);
    return {
      navbarData: navbarDoc ? JSON.parse(JSON.stringify(navbarDoc)) : null,
      footerGlobalData: footerGlobalDoc ? JSON.parse(JSON.stringify(footerGlobalDoc)) : null,
      footerColumnsData: footerColumnsDocs ? JSON.parse(JSON.stringify(footerColumnsDocs)) : null,
      homeData: homeDoc ? JSON.parse(JSON.stringify(homeDoc)) : null,
      blogsData: blogDoc ? JSON.parse(JSON.stringify(blogDoc)) : null,
      coursesData: coursesDoc ? JSON.parse(JSON.stringify(coursesDoc)) : null,
      testimonialsData: testimonialDocs ? JSON.parse(JSON.stringify(testimonialDocs)) : null,
      faqData: faqDoc ? JSON.parse(JSON.stringify(faqDoc)) : null,
      locationsData: locationDocs ? JSON.parse(JSON.stringify(locationDocs)) : null,
    };
  } catch (e) {
    console.error("Failed to prefetch layout data on server:", e);
    return null;
  }
}

